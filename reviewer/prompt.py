"""Turn a pull request (or any unified diff) into the model's training format.

The model was trained on LKML: `Subject: Re: [PATCH] ...`, an optional excerpt
of the earlier thread, then the patch. A PR maps onto that directly: the PR
description plays the role of the posting's cover text, attributed to its
author the way thread messages were. Stdlib only.
"""
from __future__ import annotations

import re

from linuspr.template import TRUNC_MARK, build_input

# Training inputs were capped so prompt + review fit in 4,096 tokens; reviews
# run up to ~1,024 tokens. ~3.3 chars/token on code and email.
MAX_PROMPT_TOKENS = 3000
CHARS_PER_TOKEN = 3.3
BODY_BUDGET_CHARS = 1200  # same per-message clip as training thread context

DISCLAIMER = (
    "> **Automated review — a style imitation, not Linus Torvalds.** Generated by a LoRA "
    "fine-tune trained on public LKML review threads (github.com/nkavassalis/lkml-reviewer). "
    "Its technical claims are often wrong; verify before acting on anything here.\n\n"
)


def _clip(text: str, limit: int) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[:limit].rstrip() + " [...]"


def strip_html_comments(text: str) -> str:
    """PR templates are full of <!-- --> instructions nobody filled in."""
    return re.sub(r"<!--.*?-->", "", text, flags=re.S).strip()


def pr_input(title: str, diff: str, *, body: str = "", author: str = "author",
             max_prompt_tokens: int = MAX_PROMPT_TOKENS) -> tuple[str, bool]:
    """(user turn, truncated?). The diff loses its tail first, as in training."""
    thread = ""
    body = strip_html_comments(body)
    if body:
        thread = f"[{author}]:\n{_clip(body, BODY_BUDGET_CHARS)}"
    subject = f"Re: [PATCH] {title.strip()}" if title.strip() else "Re: [PATCH]"
    budget = int(max_prompt_tokens * CHARS_PER_TOKEN)
    fixed = len(build_input(subject, "", thread))
    room = max(budget - fixed, 500)
    truncated = len(diff) > room
    if truncated:
        diff = diff[:room].rstrip() + TRUNC_MARK
    # Export rstrips every input (scrub_mangled), so no training prompt ever
    # ended in a newline; a raw `gh pr diff` does. Match training exactly.
    return build_input(subject, diff, thread).rstrip(), truncated


def changed_files(diff: str) -> list[str]:
    return re.findall(r"^diff --git a/(\S+) ", diff, re.M)


def split_by_file(diff: str) -> list[tuple[str, str]]:
    """[(path, that file's diff)] for reviewing big PRs one file at a time."""
    chunks = re.split(r"(?m)^(?=diff --git )", diff)
    out = []
    for c in chunks:
        m = re.match(r"diff --git a/(\S+) ", c)
        if m:
            out.append((m.group(1), c))
    return out
